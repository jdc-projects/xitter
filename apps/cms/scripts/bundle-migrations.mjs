#!/usr/bin/env node
/**
 * Compile the deployed migration runner: one self-contained
 * .next/migrate/migrate.mjs bundling the Payload config, every committed
 * src/migrations/*.ts file and scripts/migrate.ts (see migrate.ts for why
 * `payload migrate` cannot run in the standalone image).
 *
 * Runs as the last step of the cms `build` script - `npm run check` and the
 * image build both fail loudly if the config graph stops bundling.
 */
import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const migrationsIndex = path.join(appDir, 'src', 'migrations', 'index.ts');
const outDir = path.join(appDir, '.next', 'migrate');
const entryFile = path.join(outDir, 'entry.ts');

if (!existsSync(migrationsIndex)) {
  throw new Error(`${migrationsIndex} missing - run \`npm run migrate:create\` first`);
}

const entry = `// Generated by scripts/bundle-migrations.mjs at build time - never edit.
import config from '../../src/payload.config.js';
import { migrations } from '../../src/migrations/index.js';
import { runMigrations } from '../../scripts/migrate.js';

await runMigrations({ config, migrations });
process.exit(0);
`;

await mkdir(outDir, { recursive: true });
await writeFile(entryFile, entry);

try {
  await build({
    entryPoints: [entryFile],
    outfile: path.join(outDir, 'migrate.mjs'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    // The standalone runtime has no node_modules to resolve against, so
    // every dependency of the config graph (payload, drizzle, pg, zod,
    // jose, @xitter/*) is bundled - all pure JS. externals are only the
    // modules this path provably never loads: drizzle-kit/api is require()d
    // lazily via createRequire (dev-push/migrate:create only), sharp is
    // reached solely by upload processing, pg-native by the optional native
    // client pg falls back from.
    external: ['drizzle-kit', 'drizzle-kit/api', 'sharp', 'pg-native'],
    // Bundled CJS deps require() node builtins from this ESM artifact.
    banner: {
      js: "import { createRequire as __cmsBundleCreateRequire } from 'node:module';\nconst require = __cmsBundleCreateRequire(import.meta.url);",
    },
    // Admin/editor packages import stylesheets for the panel UI; the runner
    // never renders, so drop asset imports from the bundle.
    loader: { '.css': 'empty', '.scss': 'empty', '.sass': 'empty' },
    logLevel: 'warning',
  });
} finally {
  await rm(entryFile, { force: true });
}

console.log(`cms migration bundle -> ${path.join(outDir, 'migrate.mjs')}`);
